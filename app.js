function loadState() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      return { checked: {}, status: {}, notes: {} };
    }
    return { checked: {}, status: {}, notes: {}, ...JSON.parse(raw) };
  } catch {
    return { checked: {}, status: {}, notes: {} };
  }
}

function saveState() {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
}

function createElement(tag, className, text) {
  const element = document.createElement(tag);
  if (className) {
    element.className = className;
  }
  if (text !== undefined) {
    element.textContent = text;
  }
  return element;
}

function getChecklistId(topicId, index) {
  return `${topicId}:${index}`;
}

function getTopicProgress(topic) {
  const total = topic.checklist.length;
  const done = topic.checklist.filter((_, index) => state.checked[getChecklistId(topic.id, index)]).length;
  return { done, total, percent: total ? Math.round((done / total) * 100) : 0 };
}

function getUniversityProgress(universityId) {
  const related = topics.filter((topic) => topic.universityId === universityId);
  const total = related.reduce((sum, topic) => sum + topic.checklist.length, 0);
  const done = related.reduce((sum, topic) => {
    return sum + topic.checklist.filter((_, index) => state.checked[getChecklistId(topic.id, index)]).length;
  }, 0);
  return { done, total, percent: total ? Math.round((done / total) * 100) : 0 };
}

function getOverallProgress() {
  const total = topics.reduce((sum, topic) => sum + topic.checklist.length, 0);
  const done = topics.reduce((sum, topic) => {
    return sum + topic.checklist.filter((_, index) => state.checked[getChecklistId(topic.id, index)]).length;
  }, 0);
  return { done, total, percent: total ? Math.round((done / total) * 100) : 0 };
}

function renderUniversities() {
  universityGrid.innerHTML = "";

  universities.forEach((university) => {
    const progress = getUniversityProgress(university.id);
    const card = createElement("article", "university-card");
    card.dataset.university = university.id;

    card.append(
      createElement("div", "card-kicker", university.shortName),
      createElement("h2", "", university.title),
      createElement("p", "", university.focus)
    );

    const facts = createElement("ul", "fact-list");
    university.facts.forEach((fact) => facts.append(createElement("li", "", fact)));
    card.append(facts);

    const progressTrack = createElement("div", "mini-progress");
    const progressBar = createElement("span");
    progressBar.style.width = `${progress.percent}%`;
    progressTrack.append(progressBar);
    card.append(progressTrack, createElement("div", "mini-stat", `${progress.percent}% - ${progress.done} из ${progress.total} пунктов`));

    const sources = createElement("ul", "source-list");
    university.sources.forEach(([label, href]) => {
      const item = createElement("li");
      const link = createElement("a", "", label);
      link.href = href;
      link.target = href.startsWith("http") ? "_blank" : "_self";
      link.rel = "noreferrer";
      item.append(link);
      sources.append(item);
    });
    card.append(sources);
    universityGrid.append(card);
  });
}

function topicMatches(topic) {
  const matchesFilter = activeFilter === "all" || topic.universityId === activeFilter;
  const haystack = [
    topic.title,
    topic.examFocus,
    ...topic.theory,
    ...topic.deepTheory.flatMap((section) => [
      section.title,
      ...(section.paragraphs || []),
      ...(section.bullets || []),
      ...(section.formulas || [])
    ]),
    ...topic.questions,
    ...topic.questionGuides.flatMap((guide) => [
      guide.answer,
      ...(guide.bullets || [])
    ]),
    ...topic.practice,
    ...topic.checklist
  ].join(" ").toLowerCase();
  return matchesFilter && haystack.includes(query.toLowerCase());
}

function renderTopics() {
  topicList.innerHTML = "";

  const visibleTopics = topics.filter(topicMatches);
  if (!visibleTopics.length) {
    topicList.append(createElement("div", "empty-state", "Ничего не найдено. Попробуй другой запрос или переключи фильтр вузов."));
    return;
  }

  visibleTopics.forEach((topic, index) => {
    const university = universities.find((item) => item.id === topic.universityId);
    const progress = getTopicProgress(topic);

    const card = createElement("article", "topic-card");
    const details = document.createElement("details");
    details.dataset.topicId = topic.id;
    details.open = useInitialOpenState ? index < 2 : openTopics.has(topic.id);

    const summary = document.createElement("summary");
    const titleWrap = createElement("div", "summary-title");
    const title = createElement("h3", "", topic.title);
    const meta = createElement("div", "topic-meta");
    meta.append(
      createElement("span", "tag", university.shortName),
      createElement("span", "tag warn", topic.examFocus)
    );
    titleWrap.append(title, meta);

    const side = createElement("div", "summary-side");
    const mini = createElement("div", "mini-progress");
    const bar = createElement("span");
    bar.style.width = `${progress.percent}%`;
    mini.append(bar);
    side.append(mini, createElement("div", "mini-stat", `${progress.percent}% - ${progress.done}/${progress.total}`));
    summary.append(titleWrap, side);

    const body = createElement("div", "topic-body");
    body.append(renderTheoryColumn(topic), renderProgressColumn(topic));

    details.append(summary, body);
    card.append(details);
    topicList.append(card);
  });
}

function renderTheoryColumn(topic) {
  const column = createElement("div");

  const theorySection = createElement("section", "topic-section");
  theorySection.append(createElement("h4", "", "Ключевая теория"));
  const theoryList = createElement("ul");
  topic.theory.forEach((item) => theoryList.append(createElement("li", "", item)));
  theorySection.append(theoryList);

  const detailedSection = renderDetailedTheory(topic);

  const questionSection = createElement("section", "topic-section");
  questionSection.append(createElement("h4", "", "Типовые вопросы"));
  questionSection.append(renderQuestionCards(topic));

  const practiceSection = createElement("section", "topic-section");
  practiceSection.append(createElement("h4", "", "Практика"));
  const practiceList = createElement("ul");
  topic.practice.forEach((item) => practiceList.append(createElement("li", "", item)));
  practiceSection.append(practiceList);

  column.append(theorySection, detailedSection, questionSection, practiceSection);
  return column;
}

function renderQuestionCards(topic) {
  const wrap = createElement("div", "question-list");

  topic.questions.forEach((question, index) => {
    const guide = topic.questionGuides[index] || {
      answer: "Сформулируй определение, объясни практический смысл и приведи короткий пример из разработки или инженерной системы.",
      bullets: ["Начни с определения.", "Поясни, где это применяется.", "Назови ограничение или типичную ошибку."]
    };

    const details = document.createElement("details");
    details.className = "question-card";

    const summary = document.createElement("summary");
    summary.append(
      createElement("span", "question-number", String(index + 1).padStart(2, "0")),
      createElement("span", "question-title", question)
    );

    const body = createElement("div", "question-body");
    body.append(createElement("p", "", guide.answer));

    if (guide.bullets?.length) {
      const list = createElement("ul");
      guide.bullets.forEach((item) => list.append(createElement("li", "", item)));
      body.append(list);
    }

    details.append(summary, body);
    wrap.append(details);
  });

  return wrap;
}

function renderDetailedTheory(topic) {
  const section = createElement("section", "topic-section deep-theory");
  section.append(createElement("h4", "", "Подробный конспект"));

  topic.deepTheory.forEach((block) => {
    const article = createElement("article", "deep-block");
    article.append(createElement("h5", "", block.title));

    (block.paragraphs || []).forEach((paragraph) => {
      article.append(createElement("p", "", paragraph));
    });

    if (block.formulas?.length) {
      const formulaList = createElement("div", "formula-list");
      block.formulas.forEach((formula) => {
        formulaList.append(createElement("div", "formula", formula));
      });
      article.append(formulaList);
    }

    if (block.bullets?.length) {
      const list = createElement("ul");
      block.bullets.forEach((item) => list.append(createElement("li", "", item)));
      article.append(list);
    }

    section.append(article);
  });

  return section;
}

function renderProgressColumn(topic) {
  const column = createElement("aside", "topic-section");
  const statusRow = createElement("label", "status-row");
  statusRow.append(createElement("span", "", "Статус темы"));
  const statusSelect = document.createElement("select");
  statusSelect.dataset.topicStatus = topic.id;

  [
    ["not-started", "Не начинал"],
    ["in-progress", "В процессе"],
    ["repeat", "Повторить"],
    ["ready", "Готово"]
  ].forEach(([value, label]) => {
    const option = document.createElement("option");
    option.value = value;
    option.textContent = label;
    option.selected = (state.status[topic.id] || "not-started") === value;
    statusSelect.append(option);
  });
  statusRow.append(statusSelect);

  const checklist = createElement("div", "checklist");
  topic.checklist.forEach((item, index) => {
    const id = getChecklistId(topic.id, index);
    const label = createElement("label", "check-item");
    const checkbox = document.createElement("input");
    checkbox.type = "checkbox";
    checkbox.checked = Boolean(state.checked[id]);
    checkbox.dataset.checkId = id;
    label.append(checkbox, createElement("span", "", item));
    checklist.append(label);
  });

  const notes = createElement("label", "notes");
  notes.append(createElement("span", "", "Мои заметки"));
  const textarea = document.createElement("textarea");
  textarea.placeholder = "Например: повторить Байеса, решить 3 задачи на графы";
  textarea.value = state.notes[topic.id] || "";
  textarea.dataset.topicNote = topic.id;
  notes.append(textarea);

  column.append(createElement("h4", "", "Что отметить"), statusRow, checklist, notes);
  return column;
}

function updateOverallProgress() {
  const progress = getOverallProgress();
  overallPercent.textContent = `${progress.percent}%`;
  overallProgressBar.style.width = `${progress.percent}%`;
  overallStats.textContent = `${progress.done} из ${progress.total} пунктов`;
}

function render() {
  renderUniversities();
  renderTopics();
  updateOverallProgress();
}

function rememberOpenTopics() {
  openTopics = new Set(
    Array.from(document.querySelectorAll(".topic-card details[data-topic-id]"))
      .filter((details) => details.open)
      .map((details) => details.dataset.topicId)
  );
  useInitialOpenState = false;
}

document.querySelectorAll("[data-filter]").forEach((button) => {
  button.addEventListener("click", () => {
    rememberOpenTopics();
    activeFilter = button.dataset.filter;
    document.querySelectorAll("[data-filter]").forEach((item) => item.classList.toggle("is-active", item === button));
    render();
  });
});

searchInput.addEventListener("input", (event) => {
  rememberOpenTopics();
  query = event.target.value.trim();
  renderTopics();
});

topicList.addEventListener("change", (event) => {
  const checkboxId = event.target.dataset.checkId;
  const statusId = event.target.dataset.topicStatus;

  if (checkboxId) {
    state.checked[checkboxId] = event.target.checked;
  }
  if (statusId) {
    state.status[statusId] = event.target.value;
  }

  saveState();
  rememberOpenTopics();
  render();
});

topicList.addEventListener("toggle", (event) => {
  if (!event.target.matches("details[data-topic-id]")) {
    return;
  }
  useInitialOpenState = false;
  if (event.target.open) {
    openTopics.add(event.target.dataset.topicId);
  } else {
    openTopics.delete(event.target.dataset.topicId);
  }
}, true);

topicList.addEventListener("input", (event) => {
  const noteId = event.target.dataset.topicNote;
  if (!noteId) {
    return;
  }
  state.notes[noteId] = event.target.value;
  saveState();
});

